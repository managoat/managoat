defmodule Fountain.MixProject do
  use Mix.Project

  def project do
    [
      app: :fountain,
      version: "0.39.2",
      build_path: "../../_build",
      config_path: "../../config/config.exs",
      deps_path: "../../deps",
      lockfile: "../../mix.lock",
      elixir: "~> 1.18",
      elixirc_paths: elixirc_paths(Mix.env()),
      compilers: unused_compiler() ++ Mix.compilers(),
      unused: unused_config(),
      start_permanent: Mix.env() == :prod,
      aliases: aliases(),
      deps: deps(),
      listeners: [Phoenix.CodeReloader],
      test_coverage: coverage()
    ]
  end

  # Same file the umbrella root reads (#620). Read rather than referenced
  # through the root project because `mix test` is also run from inside this
  # directory — the documented way to run a single test file — and then the
  # root mix.exs is never loaded at all.
  defp coverage do
    Path.expand("../../coverage.exs", __DIR__) |> Code.eval_file() |> elem(0)
  end

  def application do
    [
      mod: {Fountain.Application, []},
      extra_applications: [:logger, :runtime_tools]
    ]
  end

  # `MIX_UNUSED=1 MIX_ENV=dev mix compile --force`, from this directory, adds
  # the mix_unused tracer, which reports every public function no compiled
  # module calls. Off by default because the tracer sees only static calls
  # inside this app: router dispatch, LiveView and OTP callbacks, protocol
  # impls and the tests all read as "nobody calls this".
  # The report is advisory (`.github/workflows/dead-code.yml` publishes it
  # monthly; `scripts/dead-code.sh` runs it here) and never gates anything.
  # The ignore list below drops the shapes that are never dead, so a reader
  # starts at the plausible ones. Read CONTRIBUTING.md, "Finding dead code",
  # before acting on a line of it.
  defp unused_compiler do
    if System.get_env("MIX_UNUSED") in ["1", "true"], do: [:unused], else: []
  end

  defp unused_config do
    [
      # mix_unused 0.4.1 cannot select analyzers here. scripts/dead-code.sh
      # filters its Private advice: a same-module caller is not dead code.
      ignore: [
        # Generated by protocols, structs, schemas and `use` macros.
        ~r/^Jason\.Encoder\./,
        ~r/^Inspect\./,
        {:_, ~r/^__/, :_},
        # Callbacks: OTP, Plug, Phoenix, LiveView, Ecto migrations, Oban.
        {:_,
         ~r/^(init|handle_(call|cast|info|continue|event|params|async)|terminate|code_change|format_status)$/,
         :_},
        {:_,
         ~r/^(mount|render|update|update_many|preload|start_link|child_spec|call|perform|up|down|change)$/,
         :_},
        # Router-dispatched: every controller action, LiveView, view and plug.
        ~r/^FountainWeb\..*(Controller|Live|HTML|JSON|Plugs\.|Router|Endpoint)/,
        # Ecto.Repo, Swoosh.Mailer and the Managoat `use` macros generate the
        # whole surface.
        Fountain.Repo,
        Fountain.Mailer,
        Fountain.OAuth
      ]
    ]
  end

  defp elixirc_paths(:test), do: ["lib", "test/support"]
  defp elixirc_paths(_), do: ["lib"]

  defp deps do
    [
      # The dead-code report (scripts/dead-code.sh). A compiler tracer, so it
      # has to be a dep of this app rather than of the umbrella root, and dev
      # only: the report reads the shipped tree, and the test env would count
      # every test as a caller.
      {:mix_unused, "~> 0.4", only: :dev, runtime: false},
      # The managoat_* component libraries (decisions/0037, #1345). Each is
      # Apache-2.0, carries no reference back into Fountain, started life as an
      # app in this umbrella and has graduated to a managoat/managoat_<name>
      # repository that publishes to hex from its own CI. The pins are
      # patch-level within each library's current minor release while everything
      # is 0.x: a new minor reaches Fountain only when someone bumps its pin here.
      #
      # Four more (acp, oauth, runtimes, sandbox) were folded back into lib/managoat/
      # on 2026-10-15 (decisions/0037's addendum): their modules keep the
      # Managoat.* names, and a change to them is a Fountain PR. managoat_docs
      # left with the manual, which is a static build in site/ since
      # 2026-10-15 (decisions/0081); broker is the one library left.
      {:managoat_broker, "~> 0.19.1"},
      # The Sprites SDK behind Managoat.Sandbox.Sprites, pinned exactly: 0.2.2
      # changed a contract in a patch release (a stream that closes without an
      # exit frame became `{:error, _, :closed_before_exit}` where 0.2.0
      # synthesised `{:exit, _, 0}`). `Managoat.Sandbox` says the same thing,
      # and test/managoat/sandbox/sprites/protocol_contract_test.exs guards the
      # two frame semantics it depends on; a bump runs it first.
      {:sprites, "0.2.2"},
      {:sentry, "~> 13.3"},
      {:phoenix, "~> 1.8.5"},
      {:phoenix_ecto, "~> 4.5"},
      {:ecto_sql, "~> 3.13"},
      {:postgrex, ">= 0.0.0"},
      {:phoenix_live_dashboard, "~> 0.8.3"},
      {:telemetry_metrics, "~> 1.0"},
      {:telemetry_metrics_prometheus_core, "~> 1.2"},
      {:telemetry_poller, "~> 1.0"},
      {:jason, "~> 1.2"},
      {:bandit, "~> 1.5"},
      {:remote_ip, "~> 1.2"},
      {:oban, "~> 2.19"},
      {:open_api_spex, "~> 3.21"},
      # The opentelemetry_* family depends on complex Erlang/rebar3 cross-dep includes
      # (otel_sampler.hrl, grpcbox, chatterbox). They compile correctly in CI
      # (Alpine/musl OTP) but fail with rebar3 bare compile in some dev environments.
      # opentelemetry_api is the only one needed at compile time (for the @decorate macros);
      # the SDK also runs in tests to catch span lifecycle errors; exporters are prod-only.
      {:opentelemetry, "~> 1.5", only: [:prod, :test]},
      {:opentelemetry_api, "~> 1.4"},
      {:opentelemetry_exporter, "~> 1.8", only: :prod},
      {:opentelemetry_phoenix, "~> 2.0", only: :prod},
      {:opentelemetry_ecto, "~> 1.2", only: :prod},
      {:req, "~> 0.5"},
      # New Fountain deps
      {:bcrypt_elixir, "~> 3.0"},
      {:swoosh, "~> 1.17"},
      # SMTP delivery, so a self-hoster is not obliged to use a SaaS provider.
      {:gen_smtp, "~> 1.2"},
      {:ueberauth, "~> 0.10"},
      {:ueberauth_github, "~> 0.8"},
      # Test / dev
      {:sobelow, "~> 0.13", only: [:dev, :test], runtime: false},
      {:mimic, "~> 2.3", only: :test},
      {:lazy_html, ">= 0.1.0", only: :test},
      {:stream_data, "~> 1.1", only: [:dev, :test]}
    ]
  end

  defp aliases do
    [
      setup: ["deps.get", "ecto.setup"],
      "ecto.setup": ["ecto.create", "ecto.migrate", "run priv/repo/seeds.exs"],
      "ecto.reset": ["ecto.drop", "ecto.setup"]
    ]
  end
end
